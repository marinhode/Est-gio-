-- Número de tombo: identificação fixa de cada planta no herbário digital (LSI 0001, LSI 0002...).
begin;
alter table public.plantas add column tombo int generated by default as identity;
-- Numera as existentes em ordem alfabética, para a sequência ficar previsível
with ordem as (select slug, row_number() over (order by nome_popular) n from public.plantas)
update public.plantas p set tombo = o.n from ordem o where o.slug = p.slug;
alter table public.plantas add constraint plantas_tombo_key unique (tombo);
select setval(pg_get_serial_sequence('public.plantas', 'tombo'), (select max(tombo) from public.plantas));
commit;
